GRAVE = ((1, -2), (2, -1))
ACUTE = ((2, -2), (1, -1))
# Italian. Lower case keeps its accent in the ascender rows; capitals need the two rows above them.
ACCENTS = {
    "\u00e0": ".#../..#./.##./...#/.###/#..#/.###", "\u00e8": ".#../..#./.##./#..#/####/#.../.###",
    "\u00e9": "..#./.#../.##./#..#/####/#.../.###", "\u00ec": "#./.#/.#/.#/.#/.#/.#",
    "\u00f2": ".#../..#./.##./#..#/#..#/#..#/.##.", "\u00f9": ".#../..#./#..#/#..#/#..#/#..#/.###",
}
CAP_ACCENTS = {"\u00c0": ("A", GRAVE), "\u00c8": ("E", GRAVE), "\u00c9": ("E", ACUTE), "\u00cc": ("I", GRAVE),
               "\u00d2": ("O", GRAVE), "\u00d9": ("U", GRAVE)}
GLYPHS = {**CAPS, **LOWER, **PUNCT, **ACCENTS}
CW, CH = 6, 12
TOP = 2  # rows of headroom above a glyph's own first row
COLS = 16
CHARS = [chr(c) for c in range(32, 127)] + list(ACCENTS) + list(CAP_ACCENTS)

img = Image.new("RGBA", (CW * COLS, CH * ((len(CHARS) + COLS - 1) // COLS)), (0, 0, 0, 0))
px = img.load()
widths = []
for i, ch in enumerate(CHARS):
    gx = (i % COLS) * CW
    gy = (i // COLS) * CH + TOP
    rows = GLYPHS.get(CAP_ACCENTS[ch][0] if ch in CAP_ACCENTS else ch)
    if rows is None:
        widths.append(3)
        continue
    rows = rows.split("/")
    widths.append(max(len(r) for r in rows))
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == "#":
                px[gx + x, gy + y] = (255, 255, 255, 255)
    if ch in CAP_ACCENTS:
        for x, y in CAP_ACCENTS[ch][1]:
            px[gx + x, gy + y] = (255, 255, 255, 255)
img.save("assets/gfx/font.png")
with open("scripts/ui/font_data.gd", "w") as f:
    f.write("class_name FontData\nextends RefCounted\n## Generated by tools/gen_font.py\n\n")
    f.write("const WIDTHS: Array[int] = " + str(widths) + "\n\n")
    f.write("## Characters past plain ASCII, as unicode code: index into WIDTHS and the atlas.\n")
    extra = {ord(c): 95 + i for i, c in enumerate(CHARS[95:])}
    f.write("const EXTRA := " + str(extra) + "\n")
print("font ok", img.size, len(CHARS))
